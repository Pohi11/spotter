"""Exports EuroSAT holdout tiles and their synthetic degradations for the dashboard's
classify panel (dashboard spec: "Demo samples are generated with the drift experiment's
degradations"). Each degraded file is exactly `degrade_jpeg`'s output, the function the
drift experiment uses, so the panel shows the same degradations the experiment measured.

It also writes the demo page's scenario bundles (see export_scenario).

Usage: spotter-demo-samples [--data data] [--out dashboard/public/samples]
                            [--scenario-out dashboard/public/scenario]
"""

import argparse
import base64
import json
import random
from pathlib import Path

from spotter_model import CLASSES

from spotter_trainer import data
from spotter_trainer.degrade import KINDS, degrade_jpeg
from spotter_trainer.splits import split

STRENGTHS = (0.5, 1.0)
SEED = 42  # the training split's seed: samples come from its holdout part


def export(images_dir: Path, out: Path, per_class: int = 1) -> dict:
    """Write one clean JPEG per class plus each degradation at each strength, and a
    manifest. Returns the manifest."""
    holdout = split(data.list_images(images_dir), seed=SEED).holdout
    by_class: dict[str, list[str]] = {c: [] for c in CLASSES}
    for path in holdout:
        by_class[path.split("/")[0]].append(path)
    samples = []
    for name in CLASSES:
        picks = sorted(by_class[name])
        random.Random(f"{SEED}-{name}").shuffle(picks)
        for path in picks[:per_class]:
            sid = Path(path).stem.lower()
            source = (images_dir / path).read_bytes()
            folder = out / sid
            folder.mkdir(parents=True, exist_ok=True)
            variants = [{"degradation": "none", "strength": 0.0, "file": f"{sid}/clean.jpg"}]
            (folder / "clean.jpg").write_bytes(source)
            for kind in KINDS:
                for strength in STRENGTHS:
                    file = f"{sid}/{kind}-{int(strength * 100)}.jpg"
                    (out / file).write_bytes(degrade_jpeg(source, kind, strength, seed=0))
                    variants.append({"degradation": kind, "strength": strength, "file": file})
            samples.append({"id": sid, "true_class": name, "source": path, "variants": variants})
    manifest = {
        "about": "EuroSAT RGB holdout tiles (split seed 42) and their degradations from "
        "spotter_trainer.degrade.degrade_jpeg (seed 0). Generated by spotter-demo-samples.",
        "dataset": "EuroSAT (Helber et al., 2019), MIT License",
        "samples": samples,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8")
    return manifest


SCENARIO_TILES = 300


def export_scenario(images_dir: Path, out: Path, count: int = SCENARIO_TILES) -> dict[str, dict]:
    """Write the demo page's scenario set (dashboard spec: "Scenario tiles are a fixed
    sample of the holdout split"): `count` holdout tiles drawn at random with a fixed seed,
    so the class mix follows the split's, as one bundle per variant: `clean.json` and
    `<degradation>.json` at full strength. Every bundle lists the same tiles in the same
    order; tile i is degraded with seed i, as in the drift experiment. Returns the bundles."""
    holdout = sorted(split(data.list_images(images_dir), seed=SEED).holdout)
    picks = random.Random(f"{SEED}-scenario").sample(holdout, min(count, len(holdout)))
    sources = [(images_dir / p).read_bytes() for p in picks]
    about = (
        f"{len(picks)} EuroSAT RGB holdout tiles (split seed {SEED}), drawn at random with a "
        "fixed seed. Degraded tiles are spotter_trainer.degrade.degrade_jpeg at strength 1 "
        "with seed = position. Generated by spotter-demo-samples."
    )
    out.mkdir(parents=True, exist_ok=True)
    bundles = {}
    for variant in ("clean", *KINDS):
        tiles = []
        for i, (path, source) in enumerate(zip(picks, sources, strict=True)):
            jpeg = source if variant == "clean" else degrade_jpeg(source, variant, 1.0, seed=i)
            tiles.append(
                {
                    "id": Path(path).stem.lower(),
                    "cls": path.split("/")[0],
                    "jpeg": base64.b64encode(jpeg).decode("ascii"),
                }
            )
        bundle = {
            "about": about,
            "variant": variant,
            "strength": 0.0 if variant == "clean" else 1.0,
            "tiles": tiles,
        }
        (out / f"{variant}.json").write_text(
            json.dumps(bundle, separators=(",", ":")) + "\n", encoding="utf-8"
        )
        bundles[variant] = bundle
    return bundles


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--data", default="data", type=Path)
    p.add_argument("--out", default=Path("dashboard/public/samples"), type=Path)
    p.add_argument("--scenario-out", default=Path("dashboard/public/scenario"), type=Path)
    a = p.parse_args()
    images = data.download(a.data)
    manifest = export(images, a.out)
    print(f"wrote {sum(len(s['variants']) for s in manifest['samples'])} files to {a.out}")
    bundles = export_scenario(images, a.scenario_out)
    tiles = len(bundles["clean"]["tiles"])
    print(f"wrote {len(bundles)} scenario bundles of {tiles} tiles to {a.scenario_out}")


if __name__ == "__main__":
    main()
